# 1. IMPORT REQUIRED LIBRARIES

import time
import numpy as np
import matplotlib.pyplot as plt

# 2. DEFINE BENCHMARK FUNCTION

def run_advanced_benchmark():

    print("=" * 65)
    print("       VISIONPORT LIFECYCLE BENCHMARK")
    print("=" * 65)

    print("\nRunning VisionPort Lifecycle Component Breakdown Benchmark...")

    # 3. CONCURRENCY LEVELS

    concurrency_levels = [1, 4, 8, 16]

    # 4. SIMULATED LATENCIES IN MILLISECONDS

    ingress_latencies = [1.2, 1.5, 2.1, 3.4]

    preprocessing_latencies = [4.5, 4.8, 5.2, 6.0]

    gpu_inference_latencies = [8.3, 9.1, 11.5, 15.2]

    postprocessing_latencies = [1.4, 1.6, 1.9, 2.3]

    # 5. CALCULATE TOTAL LATENCY

    total_latencies = []

    for i in range(len(concurrency_levels)):

        total = (
            ingress_latencies[i]
            + preprocessing_latencies[i]
            + gpu_inference_latencies[i]
            + postprocessing_latencies[i]
        )

        total_latencies.append(total)

    # 6. DISPLAY BENCHMARK RESULTS

    print("\nLIFECYCLE COMPONENT BREAKDOWN")
    print("-" * 65)

    print(
        f"{'Concurrency':<15}"
        f"{'Ingress':<12}"
        f"{'Preprocess':<12}"
        f"{'GPU':<12}"
        f"{'Postprocess':<13}"
        f"{'Total':<10}"
    )

    print("-" * 65)

    for i in range(len(concurrency_levels)):

        print(
            f"{concurrency_levels[i]:<15}"
            f"{ingress_latencies[i]:<12}"
            f"{preprocessing_latencies[i]:<12}"
            f"{gpu_inference_latencies[i]:<12}"
            f"{postprocessing_latencies[i]:<13}"
            f"{total_latencies[i]:<10.1f}"
        )

    # 7. GENERATE STACKED BAR CHART

    x = np.arange(len(concurrency_levels))

    width = 0.55

    fig, ax = plt.subplots(figsize=(10, 6))

    ax.bar(
        x,
        ingress_latencies,
        width,
        label="API Ingress (FastAPI)"
    )

    ax.bar(
        x,
        preprocessing_latencies,
        width,
        bottom=ingress_latencies,
        label="Preprocessing (OpenCV/NumPy)"
    )

    bottom_gpu = (
        np.array(ingress_latencies)
        + np.array(preprocessing_latencies)
    )

    ax.bar(
        x,
        gpu_inference_latencies,
        width,
        bottom=bottom_gpu,
        label="GPU Inference (TensorRT)"
    )

    bottom_post = (
        bottom_gpu
        + np.array(gpu_inference_latencies)
    )

    ax.bar(
        x,
        postprocessing_latencies,
        width,
        bottom=bottom_post,
        label="Postprocessing & NMS"
    )

    # 8. CHART LABELS

    ax.set_ylabel(
        "Latency (Milliseconds)",
        fontsize=12,
        fontweight="bold"
    )

    ax.set_xlabel(
        "Concurrency Level",
        fontsize=12,
        fontweight="bold"
    )

    ax.set_title(
        "VisionPort CO1 Lifecycle Stage Breakdown Across Concurrency",
        fontsize=14,
        fontweight="bold",
        pad=15
    )

    ax.set_xticks(x)

    ax.set_xticklabels(
        [str(c) for c in concurrency_levels]
    )

    ax.legend(loc="upper left", frameon=True)

    ax.grid(
        axis="y",
        linestyle="--",
        alpha=0.7
    )

    # 9. ADD TOTAL LATENCY VALUES

    for i in range(len(concurrency_levels)):

        ax.text(
            x[i],
            total_latencies[i] + 0.5,
            f"{total_latencies[i]:.1f} ms",
            ha="center",
            va="bottom",
            fontweight="bold",
            fontsize=10
        )

    plt.tight_layout()

    # 10. SAVE GRAPH

    output_filename = "visionport_lifecycle_breakdown.png"

    plt.savefig(
        output_filename,
        dpi=300,
        bbox_inches="tight"
    )

    print("\nSuccess! Lifecycle breakdown graph saved.")

    # 11. DISPLAY GRAPH

    plt.show()

    # 12. FINAL REPORT

    print("\n" + "=" * 65)
    print("             VISIONPORT FINAL REPORT")
    print("=" * 65)

    print("API Ingress Benchmark       : COMPLETED")
    print("Preprocessing Benchmark     : COMPLETED")
    print("GPU Inference Benchmark     : COMPLETED")
    print("Postprocessing Benchmark    : COMPLETED")
    print("Concurrency Testing         : COMPLETED")
    print("Stacked Bar Chart           : GENERATED")

    print("\nTotal Latencies:")

    for i in range(len(concurrency_levels)):

        print(
            f"Concurrency {concurrency_levels[i]}: "
            f"{total_latencies[i]:.1f} ms"
        )

    print("\nVISIONPORT BENCHMARK COMPLETED!")
    print("=" * 65)

    # 13. DOWNLOAD GRAPH IN GOOGLE COLAB

    from google.colab import files

    files.download(output_filename)


# 14. EXECUTE PROGRAM

if __name__ == "__main__":

    run_advanced_benchmark()